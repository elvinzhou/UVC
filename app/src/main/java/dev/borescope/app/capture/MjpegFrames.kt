package dev.borescope.app.capture

import java.io.ByteArrayOutputStream

/**
 * Makes camera MJPEG frames into self-contained JPEG files without re-encoding.
 *
 * UVC cameras may omit the Huffman tables (DHT) and rely on the JPEG standard's
 * defaults (MJPEG convention). Many viewers reject such files, so [toJpegFile]
 * inserts the standard tables when missing, plus a minimal EXIF block carrying
 * the on-screen orientation. Pixel data is copied untouched.
 */
object MjpegFrames {

    /** Returns a complete JPEG for the first [length] bytes of [frame], or null if it isn't one. */
    fun toJpegFile(frame: ByteArray, length: Int = frame.size, exifOrientation: Int = 1): ByteArray? {
        if (length < 4 || u(frame, 0) != 0xFF || u(frame, 1) != 0xD8) return null
        val hasDht = markerBeforeScan(frame, length, 0xC4) ?: return null
        val out = ByteArrayOutputStream(length + STANDARD_DHT.size + 64)
        out.write(frame, 0, 2)                       // SOI
        if (exifOrientation != 1) out.write(exifApp1(exifOrientation))
        if (!hasDht) out.write(STANDARD_DHT)
        out.write(frame, 2, length - 2)
        return out.toByteArray()
    }

    /**
     * Walks the marker segments up to Start Of Scan. Returns whether [marker]
     * occurs before it, or null if the header is malformed.
     */
    internal fun markerBeforeScan(data: ByteArray, length: Int, marker: Int): Boolean? {
        var i = 2
        while (i + 4 <= length) {
            if (u(data, i) != 0xFF) return null
            val m = u(data, i + 1)
            if (m == 0xFF) { i++; continue }                          // fill byte
            if (m == 0xDA) return false                               // SOS: header over
            if (m == marker) return true
            if (m == 0x01 || m in 0xD0..0xD7) { i += 2; continue }    // no length field
            val segLength = (u(data, i + 2) shl 8) or u(data, i + 3)
            if (segLength < 2) return null
            i += 2 + segLength
        }
        return null
    }

    /** Minimal big-endian EXIF APP1 holding only the Orientation tag. */
    internal fun exifApp1(orientation: Int): ByteArray {
        require(orientation in 1..8) { "EXIF orientation must be 1..8" }
        return intArrayOf(
            0xFF, 0xE1, 0x00, 0x22,                            // APP1, length 34
            0x45, 0x78, 0x69, 0x66, 0x00, 0x00,                // "Exif\0\0"
            0x4D, 0x4D, 0x00, 0x2A, 0x00, 0x00, 0x00, 0x08,    // TIFF "MM", 42, IFD0 at offset 8
            0x00, 0x01,                                        // 1 entry
            0x01, 0x12, 0x00, 0x03, 0x00, 0x00, 0x00, 0x01,    // Orientation, SHORT, count 1
            0x00, orientation, 0x00, 0x00,                     // value, left-justified
            0x00, 0x00, 0x00, 0x00,                            // no next IFD
        ).let { ints -> ByteArray(ints.size) { ints[it].toByte() } }
    }

    /**
     * EXIF orientation for what the viewer shows: the frame mirrored first (if
     * [mirrored]), then rotated clockwise by [rotationDegrees]. That is how the
     * preview's graphicsLayer composes scaleX and rotationZ.
     */
    fun exifOrientation(rotationDegrees: Int, mirrored: Boolean): Int {
        val quarter = (((rotationDegrees % 360) + 360) % 360) / 90
        return if (!mirrored) intArrayOf(1, 6, 3, 8)[quarter] else intArrayOf(2, 7, 4, 5)[quarter]
    }

